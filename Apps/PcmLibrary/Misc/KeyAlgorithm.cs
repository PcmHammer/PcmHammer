        /// <summary>
        /// Gets the unlock key for a CAN-bus PCM (e.g. E38).
        /// Uses the GM LAN key table which has a different opcode set to the VPW table.
        /// </summary>
        public static UInt16 GetCanKey(int algo, UInt16 seed)
        {
            if (algo < 0 || algo > 255) return 0x0000;
            if (seed == 0xFFFF) return 0xFFFF;

            int baseIdx = algo * 13;
            ushort keyValue = seed;

            for (int step = 0; step < 4; step++)
            {
                byte op = bytearray_CAN[baseIdx];
                byte b0 = bytearray_CAN[baseIdx + 1];
                byte b1 = bytearray_CAN[baseIdx + 2];

                if (op > 0x52)
                {
                    if (op == 0x6B)
                    {
                        int shift = b1 & 31;
                        keyValue = (ushort)((keyValue >> shift) | (keyValue << ((16 - shift) & 31)));
                    }
                    else if (op == 0x75)
                    {
                        keyValue = unchecked((ushort)(keyValue + (ushort)(b0 | (b1 << 8))));
                    }
                    else if (op == 0x7E)
                    {
                        ushort swapped = (ushort)((keyValue << 8) | (keyValue >> 8));
                        // Larger byte goes in the high position, smaller in the low position.
                        ushort operand = b0 >= b1
                            ? (ushort)((b0 << 8) | b1)
                            : (ushort)((b1 << 8) | b0);
                        keyValue = unchecked((ushort)(swapped + operand));
                    }
                    else if (op == 0x98)
                    {
                        keyValue = unchecked((ushort)(keyValue - (ushort)((b0 << 8) | b1)));
                    }
                    else if (op == 0xF8)
                    {
                        keyValue = unchecked((ushort)(keyValue - (ushort)(b0 | (b1 << 8))));
                    }
                    // unrecognized opcode: no-op
                }
                else
                {
                    if (op == 0x05)
                    {
                        keyValue = (ushort)((keyValue << 8) | (keyValue >> 8));
                    }
                    else if (op == 0x14)
                    {
                        keyValue = unchecked((ushort)(keyValue + (ushort)((b0 << 8) | b1)));
                    }
                    else if (op == 0x2A)
                    {
                        keyValue = b0 < b1
                            ? unchecked((ushort)(~keyValue + 1))
                            : (ushort)(~keyValue);
                    }
                    else if (op == 0x37)
                    {
                        keyValue = (ushort)(keyValue & (ushort)(b0 | (b1 << 8)));
                    }
                    else if (op == 0x4C)
                    {
                        int shift = b0 & 31;
                        keyValue = (ushort)((keyValue << shift) | (keyValue >> ((16 - shift) & 31)));
                    }
                    else if (op == 0x52)
                    {
                        keyValue = (ushort)(keyValue | (ushort)(b0 | (b1 << 8)));
                    }
                    // unrecognized opcode: no-op
                }

                baseIdx += 3;
            }

            return keyValue;
        }

