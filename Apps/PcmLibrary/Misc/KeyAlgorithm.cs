        /// <summary>
        /// Gets the unlock key for the given bus protocol, algorithm index and seed. The protocol
        /// selects the key table: Vpw uses the original VPW algorithm, Can500k uses the GMLAN
        /// algorithm. Lets a single unlock flow serve both buses from the PCM's definition.
        /// </summary>
        public static UInt16 GetKey(BusProtocol protocol, int algo, UInt16 seed)
        {
            return protocol == BusProtocol.Can500k
                ? GetCanKey(algo, seed)
                : GetKey(algo, seed);
        }

        /// <summary>
        /// Gets the unlock key from the given algorithm index and seed.
        /// </summary>
        /// <remarks>
        /// Updated with correct keygenerator that will support all algos.
        /// Updated January 10, 2020 - Gampy <pcmhacking.net>
        ///   Added algorithm index bounds checking, removed GetKey_?() hacks and removed unused elements.
        /// </remarks>
        public static UInt16 GetKey(int algo, UInt16 seed)
        {
            if ((algo >= 0) && (algo <= 255))
            {
                if (seed != 0xFFFF)
                {
                    return unchecked((UInt16)KeyAlgo(seed, algo));
                }
                else
                {
                    // 0xFFFF seed is non-standard and indicates that Parameter block is not programmed
                    // so the key is also 0xFFFF. This sometimes happens after SPS flashing.
                    return 0xFFFF;
                }
            }
            else
            {
                return 0x0000;
            }
        }

